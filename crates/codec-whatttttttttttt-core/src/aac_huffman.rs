/// Decodes one codeword from `reader` by reading one bit at a
/// time and binary-searching the entries of the length just
/// read. Returns the matching entry.
///
/// # Errors
///
/// Returns `Truncated` when the stream ends mid-codeword and
/// `InvalidData` when no codeword of any length matches (a
/// corrupt stream, or a codeword the book does not contain).
fn decode_codeword(
    reader: &mut BitReader<'_>,
    entries: &[HuffmanEntry],
    len_start: &[u16; 21],
) -> Result<HuffmanEntry> {
    let mut code: u32 = 0;
    for len in 1..=HUFFMAN_MAX_LEN as usize {
        code = (code << 1) | u32::from(reader.read_bit()?);
        let start = len_start[len] as usize;
        let end = len_start[len + 1] as usize;
        if start == end {
            continue;
        }
        let slice = &entries[start..end];
        // Entries of one length are sorted by code.
        let found = slice.binary_search_by(|entry| entry.code.cmp(&code));
        if let Ok(index) = found {
            return Ok(slice[index]);
        }
    }
    Err(Error::InvalidData {
        offset: reader.bit_position() / 8,
        detail: "aac huffman codeword not found in codebook",
    })
}

/// Reads the escape extension for a codebook-11 value of
/// magnitude 16 (ISO/IEC 13818-7 section 8.5.3.3): a unary
/// count of 1-bits (starting at 4, stopping at the first 0,
/// at most 15), then that many value bits, forming
/// `offset | (1 << count)`. A count of 16 or more is an error.
///
/// # Errors
///
/// Returns `Truncated` when the stream ends mid-escape and
/// `InvalidData` when the unary count reaches 16.
// The casts below are bounded by construction: the escape
// count is below 16, so `offset | (1 << count)` is below
// 2^16, and the reference decoder stores the result in an
// i16 (values above the codebook-11 largest absolute value,
// 2047, are out of range for valid streams).
#[allow(clippy::cast_possible_wrap, clippy::cast_possible_truncation)]
fn read_escape(reader: &mut BitReader<'_>, magnitude: i16) -> Result<i16> {
    let negative = magnitude < 0;
    if magnitude.unsigned_abs() != 16 {
        return Ok(magnitude);
    }
    let mut count: u32 = 4;
    while count < 16 {
        if !reader.read_bit()? {
            break;
        }
        count += 1;
    }
    if count >= 16 {
        return Err(Error::InvalidData {
            offset: reader.bit_position() / 8,
            detail: "aac codebook 11 escape count reaches 16",
        });
    }
    let offset = reader.read_bits(count)?;
    let value = (offset | (1 << count)) as i32;
    Ok(if negative {
        -value as i16
    } else {
        value as i16
    })
}

/// Decodes one spectral value group from `reader` with
/// `codebook` (1..=11): four values for codebooks 1-4, two for
/// codebooks 5-11 (the last two slots are 0). Magnitude books
/// read a sign bit for every nonzero value; codebook 11 reads
/// the escape extension for values of magnitude 16.
///
/// # Errors
///
/// Returns the same errors as `decode_codeword`, and
/// `InvalidArgument` for a codebook number outside 1..=11.
pub fn decode_spectral(reader: &mut BitReader<'_>, codebook: u8) -> Result<[i16; 4]> {
    let (entries, len_start) = spectral_table(codebook)?;
    let entry = decode_codeword(reader, entries, len_start)?;
    let mut values = [entry.x, entry.y, entry.v, entry.w];
    if huffman_is_magnitude(codebook) {
        for value in &mut values {
            if *value != 0 && reader.read_bit()? {
                *value = -*value;
            }
        }
    }
    if codebook == 11 {
        values[0] = read_escape(reader, values[0])?;
        values[1] = read_escape(reader, values[1])?;
    }
    Ok(values)
}

/// Decodes one scalefactor delta from `reader` (ISO/IEC
/// 13818-7 section 8.5.3.1): the table value minus 60.
