// The codeword tables below are machine-generated data (see
// /tmp/gen_aac_huffman.py): the code values are raw 19-bit
// codewords, so the literal-readability lint does not apply
// to this file.
#![allow(clippy::unreadable_literal)]

//! AAC Huffman codebooks: spectral codebooks 1-11 and the
//! scalefactor codebook (ISO/IEC 13818-7 Annex B).
//!
//! The codeword assignments are normative data from ISO/IEC
//! 13818-7 Annex B: each entry below is one (codeword, length,
//! symbols) triple from the standard's tables. The numbers were
//! recovered from the published codeword assignments and
//! re-expressed here in a flat format sorted by (length,
//! codeword), with a per-length start index so decoding is a
//! binary search over the entries of the length just read.
//! The decode walk (read one bit at a time, look the accumulated
//! codeword up, read sign bits for magnitude books, read the
//! escape extension for codebook 11) follows the algorithm in
//! ISO/IEC 13818-7 section 8.5.3 and the FAAD2 reference
//! decoder's `huffman.c` (GPL-2.0; no FAAD2 code is copied here,
//! only the standard's codeword assignments are used).
//!
//! Every book was validated as a complete prefix code (Kraft sum
//! exactly 1, unique codewords) when the tables were generated:
//! cb1-6 have 81 entries, cb7-8 have 64, cb9-10 have 169, cb11
//! has 289, and the scalefactor book has 121 entries (values
//! 0..=120, the decoded delta is value - 60).

use crate::bitreader::BitReader;
use crate::error::{Error, Result};

/// One Huffman codeword: the code bits right-aligned in `code`,
/// the codeword length in bits, and the decoded symbols (four
/// values for codebooks 1-4, two for codebooks 5-11; unused
/// slots are 0).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct HuffmanEntry {
    /// Codeword bits, right-aligned.
    pub code: u32,
    /// Codeword length in bits.
    pub len: u8,
    /// First decoded value.
    pub x: i16,
    /// Second decoded value.
    pub y: i16,
    /// Third decoded value (codebooks 1-4 only).
    pub v: i16,
    /// Fourth decoded value (codebooks 1-4 only).
    pub w: i16,
}

/// True when the codebook decodes four values per codeword
/// (codebooks 1-4); false for pairs (codebooks 5-11).
#[must_use]
pub const fn huffman_is_quad(codebook: u8) -> bool {
    matches!(codebook, 1..=4)
}

/// True when the codebook's table values are magnitudes and a
/// sign bit follows in the stream for every nonzero value
/// (codebooks 3, 4, 7, 8, 9, 10, 11). Codebooks 1, 2, 5, 6
/// carry signed values in the table itself.
#[must_use]
pub const fn huffman_is_magnitude(codebook: u8) -> bool {
    matches!(codebook, 3 | 4 | 7 | 8 | 9 | 10 | 11)
}

